#!/usr/bin/env python3
"""Turn QD Up oracle start states into C for tests/qdup-physics.

  qdup_gen_state.py ORACLE_ROOT SHOT...

writes tests/qdup-physics/gen/:
  shot_<name>.c  struct shot_start: the balls just after the stroke (8.24 and
                 16.16, rounded to nearest), the globals the physics reads and
                 the hit_ball inputs, from <ORACLE_ROOT>/<name>/state.json
  csh_ram.c      the cushion file (NMS's .csh layout, see load_cushions in
                 FIXBALL.C) made from the cushion and pocket tables as they
                 were in the 1996 build's RAM, corrupted rows included,
                 converted as COMMON.C does: (long)(value*0x1000000) for x
                 and y, (long)(angle*0x10000) for angles, saturating like the
                 1996 soft-float conversion (127.99999994 for 444 m)
  csh_text.c     the same file made from the table's text cushion file read
                 one point per line (COMMON.C with the restored break);
                 min_value goes through a float, as in init_cushions

All shots must share one table (Potters US): the RAM tables are compared.
"""
import json, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, '..', 'tests', 'qdup-physics', 'gen')
TEXT_TABLE = os.path.join(os.environ.get('QDUP_DATA', os.path.join(HERE, '..', 'build/originals/qdup/WORK/SONY/POOL2')),
                          'TABLES/POTTERS/USTABLE.BMP')
NAMES = ['cushions_y1', 'cushions_x2', 'cushions_x3', 'cushions_y4']


def h2d(h):
    return struct.unpack('<d', struct.pack('<Q', int(h, 16)))[0]


def trunc_sat(v, scale):
    """C (long)(v*scale), saturating to the 32-bit range."""
    p = v * scale
    if p >= 2**31 - 1:
        return 2**31 - 1
    if p <= -2**31:
        return -2**31
    return int(p)


def rnd(v, scale):
    p = v * scale
    r = int(p + 0.5) if p >= 0 else -int(-p + 0.5)
    return max(-2**31, min(2**31 - 1, r))


def fl(v):
    return struct.unpack('<f', struct.pack('<f', v))[0]


def csh_bytes(hdr, pockets, tables):
    out = struct.pack('<7i', *hdr)
    for p in pockets:
        out += struct.pack('<3i', trunc_sat(p[0], 0x1000000), trunc_sat(p[1], 0x1000000),
                           trunc_sat(p[2], 0x1000000))
    for n in NAMES:
        for x, y, a in tables[n]:
            out += struct.pack('<3i', trunc_sat(x, 0x1000000), trunc_sat(y, 0x1000000),
                               trunc_sat(a, 0x10000))
    return out


def c_blob(name, data, comment):
    words = struct.unpack('<%di' % (len(data) // 4), data)
    lines = ['/* generated by tools/qdup_gen_state.py: %s */' % comment,
             '/* cushion file in the .csh layout load_cushions reads */',
             'const long %s[%d] = {' % (name, len(words))]
    for i in range(0, len(words), 8):
        lines.append('\t' + ', '.join('%d' % w for w in words[i:i + 8]) + ',')
    lines += ['};', 'const unsigned long %s_size = sizeof(%s);' % (name, name), '']
    return '\n'.join(lines)


def text_tables(path):
    toks = open(path, 'rb').read().decode('latin-1').split()
    sizes = {'cushions_y1': 1000, 'cushions_x2': 2000, 'cushions_x3': 2000, 'cushions_y4': 1000}
    t = {n: [[0.0, 0.0, 0.0] for _ in range(sizes[n])] for n in NAMES}
    pockets = [[0.0, 0.0, 0.0] for _ in range(6)]
    mins = {}
    cur = None
    pk = 0
    i = 0
    while i < len(toks):
        k = toks[i]
        if k == 'bumper:':
            cur = int(toks[i + 1]); i += 2; continue
        if k == 'point:':
            t[NAMES[cur - 1]][int(toks[i + 1])] = [float(toks[i + 2]), float(toks[i + 3]), float(toks[i + 4])]
            i += 5; continue
        if k == 'pocket:':
            pk = int(toks[i + 1]); i += 2; continue
        if k == 'pocket_x:':
            pockets[pk][0] = float(toks[i + 1]); i += 2; continue
        if k == 'pocket_y:':
            pockets[pk][1] = float(toks[i + 1]); i += 2; continue
        if k == 'pocket_radius:':
            pockets[pk][2] = float(toks[i + 1]) * 1.5; i += 2; continue
        if k == 'edge_step_value:':
            mins['bumper_scale'] = float(toks[i + 1]); i += 2; continue
        if k == 'min_value:':
            mins[cur] = fl(float(toks[i + 1])); i += 2; continue
        i += 1
    # bumper 1 is min_cush_x1, 3 max_cush_y2, 2 min_cush_y3, 4 max_cush_x4
    hdr = [2000, 1000, trunc_sat(mins['bumper_scale'], 0x1000000),
           trunc_sat(mins[1], 0x1000000), trunc_sat(mins[3], 0x1000000),
           trunc_sat(mins[2], 0x1000000), trunc_sat(mins[4], 0x1000000)]
    return hdr, pockets, t


def shot_c(name, st):
    g = st['globals']
    lines = ['/* generated by tools/qdup_gen_state.py from work/oracle/%s/state.json */' % name,
             '/* stroke at route tick %d, press %s */' % (st['stroke_tick'], st['press']),
             '#include "shot.h"',
             'const struct shot_start shot = {',
             '\t"%s",' % name,
             '\t%d, %d, %d, %d, %d, %d,' % (g['LAST_BALL'], rnd(g['ball_mass'], 1 << 24),
                                           g['TABLESIZE_TYPE'], g['LOCATION'], g['GAME_TYPE'],
                                           g['SNOOKER_MODE']),
             '\t%d,\t/* time step 1/%g s */' % (rnd(1.0 / g['frame_rate'], 1 << 24), g['frame_rate']),
             '\t%d, %d, %d, %d, %d,\t/* cue_angle, butt, speed_meter %r, x_hit, y_hit */'
             % (g['cue_angle'], g['butt'], rnd(g['speed_meter'], 1 << 24), g['x_hit_pos'],
                g['y_hit_pos'], g['speed_meter']),
             '\t{']
    for b in st['balls']:
        d = {k: (h2d(v) if isinstance(v, str) else v) for k, v in b.items()}
        longs = [d[k] for k in ['graphic_type', 'obj_type', 'ball_colour', 'foul_flag', 'hitcush',
                                'numstruct', 'respot_flag', 'num', 'pocket_ball_went_down']]
        f24 = [rnd(d[k], 1 << 24) for k in ['x', 'y', 'z', 'x_prev', 'y_prev', 'z_prev',
                                           'vx', 'vy', 'vz', 'diameter', 'mass']]
        f16 = [rnd(d[k], 1 << 16) for k in ['avx', 'avy', 'avz']]
        lines.append('\t\t{ {%s}, %s, %s, %d, %d },' % (
            ', '.join(str(v) for v in longs), ', '.join(str(v) for v in f24),
            ', '.join(str(v) for v in f16), d['moving'], d['active']))
    lines += ['\t}', '};', '']
    return '\n'.join(lines)


def main():
    root = sys.argv[1]
    shots = sys.argv[2:]
    os.makedirs(GEN, exist_ok=True)
    ram = None
    for s in shots:
        st = json.load(open(os.path.join(root, s, 'state.json')))
        tabs = {n: [[h2d(v) for v in e] for e in st['cushions'][n]] for n in NAMES}
        if ram is None:
            ram = (st, tabs)
        elif tabs != ram[1]:
            sys.exit('cushion tables differ between shots')
        with open(os.path.join(GEN, 'shot_%s.c' % s), 'w') as f:
            f.write(shot_c(s, st))
    st, tabs = ram
    g = st['globals']
    hdr = [g['xpoints'], g['ypoints']] + [trunc_sat(g[k], 0x1000000) for k in
                                          ['bumper_scale', 'min_cush_x1', 'max_cush_y2',
                                           'min_cush_y3', 'max_cush_x4']]
    pockets = [[h2d(p['x']), h2d(p['y']), h2d(p['radius'])] for p in st['pockets']]
    with open(os.path.join(GEN, 'csh_ram.c'), 'w') as f:
        f.write(c_blob('csh_data', csh_bytes(hdr, pockets, tabs),
                       'cushion and pocket tables as in the 1996 build\'s RAM (Potters US)'))
    thdr, tpockets, ttabs = text_tables(TEXT_TABLE)
    if thdr != hdr:
        print('note: header from text differs from RAM:', thdr, hdr)
    for i, (a, b) in enumerate(zip(tpockets, pockets)):
        if any(abs(x - y) > 1e-12 for x, y in zip(a, b)):
            print('note: pocket %d differs: text %s ram %s' % (i, a, b))
    with open(os.path.join(GEN, 'csh_text.c'), 'w') as f:
        f.write(c_blob('csh_data', csh_bytes(thdr, tpockets, ttabs),
                       'cushion and pocket tables from TABLES/POTTERS/USTABLE.BMP, one point per line'))
    print('wrote', os.path.normpath(GEN))


if __name__ == '__main__':
    main()
