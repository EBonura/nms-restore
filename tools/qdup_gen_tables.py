#!/usr/bin/env python3
"""Generate qdup/POOL2/FIXTAB.H: the arctangent table behind FIXMATH.C.

  fix_atan_tab[1025]  atan(i / 1024) in 1/16 of an SGL angle unit (65536 units =
                  360deg, so 1/16 unit = 360/1048576 deg); fix_atan2
                  interpolates between entries.

(slSin and slCos are NMS's, in SGL.S with its table SIN_COS.TAB.)
Computed here from Python's math module, not taken from any SDK.
Written with CRLF line ends like the rest of POOL2.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'qdup', 'POOL2', 'FIXTAB.H')


def rows(vals, per=8):
    out = []
    for i in range(0, len(vals), per):
        out.append('\t' + ', '.join('%d' % v for v in vals[i:i + per]) + ',')
    return out


def main():
    fix_atan_tab = [int(round(math.atan(i / 1024) * 65536 * 16 / (2 * math.pi))) for i in range(1025)]
    lines = [
        '// RESTORE: generated by tools/qdup_gen_tables.py, do not edit.',
        '// Table for fix_atan2 in FIXMATH.C.',
        '',
        '// atan(i / 1024), in 1/16 of an SGL angle unit (1048576 = 360deg)',
        'static const long fix_atan_tab[1025] = {',
    ] + rows(fix_atan_tab) + ['};', '']
    with open(OUT, 'wb') as f:
        f.write(('\r\n'.join(lines)).encode('ascii'))
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
