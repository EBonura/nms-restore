/* Initialise PC Hardware (Memory,CD,SVGA,Mouse,Keyboard) */
/* ‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹ */

#include "globals.h"

flag init_hardware(void )
{
	// ...Initialise Memory...

	malloc(4096);
	init_heap(8);

	// ...Initialise CD...

	music_on=NO;
	selected_cdtrack=1;
	last_cdtrack=10;

	// ...Initialize SVGA...

	if( SVGA_init()==FAIL)
	{
		printf("Could not Initialise SVGA\n");
		exit(-1);
	}

	if(SVGA_is_mode_available(0x101)==NO)
	{
		printf("SVGA 640x480 mode 101h is not available\n");
		SVGA_uninit();
		exit(-1);
	}

	SVGA_set_mode(0x101);

	// ...Initialise mouse...
		
	reset_mouse_driver();

	// ...Initialise Keyboard...

	installkey();

	return OK;
}
	
