/* Play Sample */
/* ‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹‹ */

void play_sample(long channel,char *source,long length)
{
	if(sound_active==FALSE) return;

	if( AIL_sample_status(sample_handles[channel])==SMP_PLAYING ) return;

	AIL_init_sample              ( sample_handles[channel]                  );
// AIL_set_sample_type          ( sample_handles[channel], DIG_F_MONO_8, 0 );
// AIL_set_sample_type          ( sample_handles[channel], DIG_F_MONO_16, 0 );
   AIL_set_sample_type          ( sample_handles[channel], DIG_F_MONO_16, DIG_PCM_SIGN );
	AIL_set_sample_address       ( sample_handles[channel], source, length  );
	AIL_set_sample_playback_rate ( sample_handles[channel], 11025           );
	AIL_set_sample_volume        ( sample_handles[channel], 127 );
	AIL_start_sample(sample_handles[channel]);
}

